"""
Frame dependence of the torsion divisor sum  D_I(m,n,l) = sum_{s|I} s d_*(m/s^2, n, l/s).

Pure exact integer arithmetic (no floats, no d_* needed for the structural statements).

Dictionary used throughout
--------------------------
A frame (Q,P) of a rank-2 even lattice L gives the integral binary quadratic form
    f = (a,b,c) = (m, l, n),      f(x,y) = a x^2 + b x y + c y^2 = q(xQ+yP)/2,
    disc f = b^2 - 4ac = -Delta,  Gram(L) = [[2m, l],[l, 2n]],  det Gram = Delta.
Changing frame by A = [[x,u],[y,v]] in GL(2,Z) replaces f by f o A.

The s-th summand of D_I is  s * d_*(N_s)  with  N_s = Z(Q/s) + Z P,  whose form is
    (m/s^2, l/s, n) = f o diag(1/s, 1).
N_s is an even lattice iff s^2 | m and s | l.

So: "I-admissible frame" == "I^2 | m and I | l" == "N_I is an even overlattice of L of index I
with cyclic quotient generated by Q/I".

Run:   python frame_structure.py            (all experiments)
       python frame_structure.py --selftest
"""

import sys
from itertools import product

# --------------------------------------------------------------------------- #
# binary quadratic forms, exact
# --------------------------------------------------------------------------- #


def disc(f):
    a, b, c = f
    return b * b - 4 * a * c


def content(f):
    from math import gcd
    a, b, c = f
    return gcd(gcd(abs(a), abs(b)), abs(c))


def is_pos_def(f):
    a, b, c = f
    return a > 0 and disc(f) < 0


def reduce_sl(f):
    """SL(2,Z)-reduction of a positive definite integral form (a,b,c) (a>0, disc<0).
    Returns the unique reduced form: -a < b <= a <= c, and b >= 0 if a == c."""
    a, b, c = f
    assert a > 0 and disc(f) < 0, f
    D = disc(f)
    for _ in range(10 ** 6):
        if c < a:
            a, b, c = c, -b, a
            continue
        if b > a or b <= -a:
            k = (a - b) // (2 * a)          # want b + 2ak in (-a, a]
            b = b + 2 * a * k
            c = (b * b - D) // (4 * a)
            continue
        break
    assert -a < b <= a <= c, (f, (a, b, c))
    if a == c and b < 0:
        b = -b
    assert b * b - 4 * a * c == D, (f, (a, b, c))
    return (a, b, c)


def reduce_gl(f):
    """GL(2,Z)-class representative: SL-reduce, then fold b -> |b| (the form and its
    opposite are GL-equivalent).  d_* is a GL(2,Z) class function, so this is the right
    normal form for our purposes."""
    a, b, c = reduce_sl(f)
    return (a, abs(b), c)


def compose_basis(x, y):
    """Complete a primitive vector (x,y) to a basis: return (u,v) with x*v - y*u = 1."""
    from math import gcd
    assert gcd(abs(x), abs(y)) == 1, (x, y)
    # extended euclid: x*v - y*u = 1
    g, s, t = ext_gcd(x, y)          # x s + y t = g = 1
    # want x v - y u = 1 -> v = s, u = -t
    assert g == 1
    return (-t, s)


def ext_gcd(a, b):
    if b == 0:
        return (abs(a), 1 if a > 0 else -1, 0)
    g, s, t = ext_gcd(b, a % b)
    return (g, t, s - (a // b) * t)


def act(f, A):
    """f o A where A = [[x,u],[y,v]] acts on column (x,y)^T; returns new (a,b,c)."""
    a, b, c = f
    x, u, y, v = A
    na = a * x * x + b * x * y + c * y * y
    nc = a * u * u + b * u * v + c * v * v
    nb = 2 * a * x * u + b * (x * v + y * u) + 2 * c * y * v
    return (na, nb, nc)


def divisors(k):
    return [d for d in range(1, k + 1) if k % d == 0]


# --------------------------------------------------------------------------- #
# frames and admissibility
# --------------------------------------------------------------------------- #


def frame_from_primitive(f, x, y):
    """The form of L in the frame whose first vector is xQ + yP."""
    u, v = compose_basis(x, y)
    return act(f, (x, u, y, v))


def is_admissible(g, I):
    """g = (m, l, n) in some frame; is I^2 | m and I | l ?"""
    m, l, n = g
    return m % (I * I) == 0 and l % I == 0


def chain(g, I):
    """The tuple of overlattice forms (N_s) for s | I, as forms (m/s^2, l/s, n)."""
    m, l, n = g
    out = []
    for s in divisors(I):
        assert m % (s * s) == 0 and l % s == 0, (g, I, s)
        out.append((m // (s * s), l // s, n))
    return tuple(out)


def subgroup_key(x, y, I):
    """Canonical label of the cyclic subgroup <(x,y)> of (Z/I)^2 generated by (x,y)."""
    S = set()
    for k in range(I):
        S.add(((k * x) % I, (k * y) % I))
    return tuple(sorted(S))


def admissible_frames(f, I, box=None):
    """Enumerate the I-admissible frames of the lattice with form f, grouped by the
    subgroup H = <(x,y) mod I> of (Z/I)^2.  Returns dict H -> list of (x, y, g, chain).
    The vectors (x,y) range over primitive integer pairs with |x|,|y| <= box."""
    from math import gcd
    if box is None:
        box = 3 * I + 3
    out = {}
    for x in range(-box, box + 1):
        for y in range(-box, box + 1):
            if gcd(abs(x), abs(y)) != 1:
                continue
            if gcd(gcd(abs(x), abs(y)), I) != 1:
                continue
            g = frame_from_primitive(f, x, y)
            if not is_admissible(g, I):
                continue
            H = subgroup_key(x, y, I)
            out.setdefault(H, []).append((x, y, g, chain(g, I)))
    return out


def value_classes(f, I, box=None):
    """For each admissible H, the tuple of GL(2,Z) classes of the chain N_s, s|I."""
    fr = admissible_frames(f, I, box)
    res = {}
    for H, lst in fr.items():
        classes = set()
        for (x, y, g, ch) in lst:
            classes.add(tuple(reduce_gl(t) for t in ch))
        res[H] = classes
    return res


# --------------------------------------------------------------------------- #
# class group helpers (primitive forms of discriminant D < 0)
# --------------------------------------------------------------------------- #


def reduced_primitive_forms(D):
    """All reduced primitive positive definite forms of discriminant D < 0 (SL classes)."""
    assert D < 0 and D % 4 in (0, 1)
    out = []
    a = 1
    while 3 * a * a <= -D:
        for b in range(-a + 1, a + 1):
            if (b * b - D) % (4 * a):
                continue
            c = (b * b - D) // (4 * a)
            if c < a:
                continue
            if a == c and b < 0:
                continue
            if content((a, b, c)) != 1:
                continue
            out.append((a, b, c))
        a += 1
    return out


def class_number(D):
    return len(reduced_primitive_forms(D))


def all_reduced_forms(D):
    """All reduced forms of discriminant D, including imprimitive ones
    (= disjoint union over g with g^2 | D and D/g^2 = 0,1 mod 4 of g * primitive of D/g^2)."""
    out = []
    g = 1
    while g * g <= -D:
        if (-D) % (g * g) == 0 and (D // (g * g)) % 4 in (0, 1):
            for f in reduced_primitive_forms(D // (g * g)):
                out.append(tuple(g * t for t in f))
        g += 1
    return out


def is_ambiguous(f):
    """[f]^2 = 1 in the class group  <=>  the reduced form has b = 0, a = b, or a = c."""
    a, b, c = reduce_sl(f)
    return b == 0 or a == b or a == c


def prime_form(p, D):
    """A form (p, b, *) of discriminant D representing p (the ideal p above p), or None."""
    for b in range(-p + 1, p + 1):
        if (b * b - D) % (4 * p) == 0:
            c = (b * b - D) // (4 * p)
            if c > 0:
                return (p, b, c)
    return None


